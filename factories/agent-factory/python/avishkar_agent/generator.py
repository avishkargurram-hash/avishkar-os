"""scaffold_agent -- the Agent Framework's generator. Produces exactly
three files from an AgentBlueprint: the blueprint itself (as JSON), a
domain module stub, and a README stub pre-filled with the 30-section
template's headings. Deliberately not "hundreds of placeholder files" --
see the Master Build Directive's explicit instruction against that.
"""

from __future__ import annotations

import dataclasses
import json
from pathlib import Path
from typing import Tuple

from .blueprint import AgentBlueprint

_AGENT_TEMPLATE_SECTIONS = (
    "Identity & Mission",
    "Responsibilities",
    "Domain Knowledge Architecture",
    "Reasoning Strategies",
    "Decision Frameworks",
    "Thinking Models",
    "Planning & Reflection",
    "Memory Policies",
    "MCP Integration Points",
    "Tool Registry",
    "Knowledge Sources",
    "Prompt Library",
    "Workflow Library",
    "Template Library",
    "Checklists",
    "Evaluation Framework",
    "Security Policies",
    "Guardrails",
    "Quality Gates",
    "Error Recovery Strategies",
    "Output Standards",
    "Communication Style",
    "Collaboration Protocols",
    "Sub-Agent Architecture",
    "Extensibility Model",
    "Testing Strategy",
    "Versioning Strategy",
    "Documentation",
    "Examples",
    "Future Roadmap",
)


def _blueprint_to_json(blueprint: AgentBlueprint) -> str:
    data = dataclasses.asdict(blueprint)
    return json.dumps(data, indent=2, sort_keys=False) + "\n"


def _readme_stub(blueprint: AgentBlueprint) -> str:
    lines = [f"# {blueprint.domain} — Chief Domain Agent", ""]
    for index, section in enumerate(_AGENT_TEMPLATE_SECTIONS, start=1):
        lines.append(f"## {index}. {section}")
        lines.append("_TODO: fill in before this agent is considered built (STANDARDS.md SS2.3)._")
        lines.append("")
    return "\n".join(lines)


def _domain_module_stub(blueprint: AgentBlueprint) -> str:
    class_name = "".join(part.capitalize() for part in blueprint.name.split("-")) + "Agent"
    return (
        f'"""{blueprint.domain} -- domain module for the {blueprint.name} Chief Domain Agent.\n\n'
        f'Generated by agent-factory\'s scaffold_agent(). Wire real tools, guardrails,\n'
        f'quality gates, and any domain-specific thinking-model extensions here --\n'
        f'this file is where domain logic lives; avishkar_agent itself never changes.\n'
        f'"""\n\n'
        f"from avishkar_agent import ChiefDomainAgent, InMemoryMemoryPolicy, ToolRegistry\n"
        f"from avishkar_agent.thinking import DEFAULT_THINKING_MODELS\n"
        f"from avishkar_router import Router\n\n\n"
        f"def build_{blueprint.name.replace('-', '_')}(router: Router) -> ChiefDomainAgent:\n"
        f'    """Construct the {blueprint.domain} Chief Domain Agent. Replace the\n'
        f"    defaults below with this domain's real tools/guardrails/quality gates.\n"
        f'    """\n'
        f"    from .blueprint import load_blueprint  # TODO: point at the real blueprint.json\n\n"
        f"    blueprint = load_blueprint()\n"
        f"    return ChiefDomainAgent(\n"
        f"        blueprint=blueprint,\n"
        f"        router=router,\n"
        f"        memory=InMemoryMemoryPolicy(),\n"
        f"        tools=ToolRegistry(),\n"
        f"        thinking_models=DEFAULT_THINKING_MODELS,\n"
        f"    )\n"
    )


def scaffold_agent(blueprint: AgentBlueprint, target_dir: Path) -> Tuple[Path, Path, Path]:
    """Writes blueprint.json, README.md, and <name>_agent.py under
    `target_dir` (typically `agents/<blueprint.name>/`). Returns the
    three paths written. Never touches avishkar_agent's own source --
    that's the whole point (see CONTRACT.md SS8).
    """
    target_dir.mkdir(parents=True, exist_ok=True)

    blueprint_path = target_dir / "blueprint.json"
    blueprint_path.write_text(_blueprint_to_json(blueprint), encoding="utf-8")

    readme_path = target_dir / "README.md"
    readme_path.write_text(_readme_stub(blueprint), encoding="utf-8")

    module_path = target_dir / f"{blueprint.name.replace('-', '_')}_agent.py"
    module_path.write_text(_domain_module_stub(blueprint), encoding="utf-8")

    return blueprint_path, readme_path, module_path
