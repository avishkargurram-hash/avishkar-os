"""Real OCR tests. extract_text() genuinely runs the Tesseract binary
on this machine against a synthetically-rendered test image (drawn
with PIL, not captured from a live screen) -- a real, non-mocked,
non-fabricated OCR test with no privacy concern, since the image is
generated by the test itself.
"""

import unittest

from avishkar_layla.vision.errors import OCRNotAvailableError
from avishkar_layla.vision.ocr import OCRResult, extract_text, is_tesseract_available


def _render_text_image(text: str):
    from PIL import Image, ImageDraw

    image = Image.new("RGB", (400, 100), color="white")
    draw = ImageDraw.Draw(image)
    draw.text((10, 30), text, fill="black")
    return image


class TestOCRAvailability(unittest.TestCase):
    def test_extract_text_raises_adapter_ready_error_when_unavailable(self):
        if is_tesseract_available():
            self.skipTest("tesseract IS available on this machine -- this test covers the opposite case")
        with self.assertRaises(OCRNotAvailableError) as ctx:
            extract_text(_render_text_image("hello"))
        self.assertIn("ADAPTER READY", str(ctx.exception))


@unittest.skipUnless(is_tesseract_available(), "tesseract binary not available in this environment")
class TestOCRReal(unittest.TestCase):
    def test_real_ocr_reads_rendered_text(self):
        image = _render_text_image("AVISHKAR LAYLA")
        result = extract_text(image)

        self.assertIsInstance(result, OCRResult)
        self.assertIn("AVISHKAR", result.text.upper())

    def test_real_ocr_produces_real_word_boxes_with_confidence(self):
        image = _render_text_image("HELLO WORLD")
        result = extract_text(image)

        self.assertGreater(len(result.words), 0)
        for word in result.words:
            self.assertGreaterEqual(word.confidence, 0.0)
            self.assertLessEqual(word.confidence, 1.0)
            self.assertGreaterEqual(word.box.x1, word.box.x0)
            self.assertGreaterEqual(word.box.y1, word.box.y0)

    def test_blank_image_produces_no_words(self):
        from PIL import Image

        blank = Image.new("RGB", (200, 100), color="white")
        result = extract_text(blank)
        self.assertEqual(result.words, ())
        self.assertEqual(result.text, "")


if __name__ == "__main__":
    unittest.main()
