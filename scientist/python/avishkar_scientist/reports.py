"""Final report composer (spec section 27).

Deterministic markdown built straight from the database -- the verdict
package already decided the label and narrative; this module only lays the
supporting record out for a human reader. No model call here.
"""

from __future__ import annotations


def _fmt_claim(row: dict) -> str:
    return f"- ({row['stance']}, {row['epistemic'].lower()}) {row['text']}"


def build_report(conn, mid: str) -> str:
    m = conn.execute("SELECT * FROM missions WHERE id=%s", (mid,)).fetchone()
    v = conn.execute("SELECT * FROM verdicts WHERE mission_id=%s ORDER BY id DESC LIMIT 1", (mid,)).fetchone()
    hyps = conn.execute("SELECT * FROM hypotheses WHERE mission_id=%s ORDER BY label", (mid,)).fetchall()
    sources = conn.execute(
        "SELECT * FROM sources WHERE mission_id=%s ORDER BY quality DESC, citation_count DESC NULLS LAST",
        (mid,)).fetchall()
    claims = conn.execute(
        "SELECT * FROM claims WHERE mission_id=%s AND status<>'UNVERIFIED' ORDER BY confidence DESC", (mid,)
    ).fetchall()
    experiments = conn.execute("SELECT * FROM experiments WHERE mission_id=%s ORDER BY id", (mid,)).fetchall()
    contras = conn.execute(
        "SELECT x.*, a.text AS a_text, b.text AS b_text FROM contradictions x "
        "JOIN claims a ON a.id=x.claim_a JOIN claims b ON b.id=x.claim_b WHERE x.mission_id=%s ORDER BY x.id",
        (mid,)).fetchall()
    critics = conn.execute(
        "SELECT * FROM critic_reports WHERE mission_id=%s AND iteration=(SELECT max(iteration) FROM "
        "critic_reports WHERE mission_id=%s) ORDER BY role", (mid, mid)).fetchall()

    lines = [f"# Research Report: {mid}", ""]
    if m["demo"]:
        lines.append("**DEMO -- SIMULATED.** Every source below is fictional (Demonium-7). "
                     "This report demonstrates the pipeline only and says nothing about the real world.")
        lines.append("")
    lines.append(f"**Question:** {m['question']}")
    lines.append("")
    lines.append(f"**Depth:** {m['research_depth']}  |  **Iterations:** {m['iteration'] + 1}  |  "
                 f"**Stop reason:** {m['stop_reason'] or '-'}")
    lines.append("")

    lines.append("## Verdict")
    if v:
        lines.append(f"**{v['label']}**")
        lines.append("")
        lines.append(v["narrative"] or v["statement"])
        lines.append("")
        lines.append(f"Confidence: {v['confidence']:.2f} ({v['evidence_strength']})  |  "
                     f"Package hash: `{v['package_sha256'][:16]}`")
        if v["council"]:
            lines.append(f"Council synthesis: {v['council'].get('label')} "
                         f"(spread {v['council'].get('spread')})")
    else:
        lines.append("No verdict was produced.")
    lines.append("")

    lines.append("## Hypotheses")
    for h in hyps:
        lines.append(f"- **{h['label']}** ({h['kind']}, {h['status']}, p={float(h['probability']):.2f}): "
                     f"{h['statement']}")
    lines.append("")

    lines.append(f"## Evidence ({len(claims)} verified claim(s))")
    for c in claims[:25]:
        lines.append(_fmt_claim(c))
    lines.append("")

    if experiments:
        lines.append("## Experiments")
        for e in experiments:
            supports = "supports H1" if e["supports"] else ("refutes H1" if e["supports"] is False else "inconclusive")
            lines.append(f"- **{e['title']}** -- {e['status']}, {supports}"
                         + (f", reproducibility {e['reproducibility']:.2f}" if e["reproducibility"] is not None else ""))
        lines.append("")

    if contras:
        lines.append("## Contradictions")
        for x in contras:
            lines.append(f"- [{x['severity']}, {x['resolution']}] \"{x['a_text'][:150]}\" vs "
                         f"\"{x['b_text'][:150]}\"" + (f" -- {x['explanation']}" if x["explanation"] else ""))
        lines.append("")

    lines.append(f"## Sources ({len(sources)} found, {sum(1 for s in sources if s['analyzed'])} analyzed)")
    for s in sources[:30]:
        tag = " [SIMULATED]" if s["demo_simulated"] else ""
        lines.append(f"- {s['title']}{tag} ({s['provider']}, {s['year'] or '?'}) "
                     f"quality={s['quality']:.2f}" + (f" doi:{s['doi']}" if s["doi"] else ""))
    lines.append("")

    if critics:
        lines.append("## Critic reviews")
        for cr in critics:
            lines.append(f"- **{cr['role']}** (score {cr['score']:.2f}): " +
                         ("; ".join(cr["issues"]) if cr["issues"] else "no issues raised"))
        lines.append("")

    lines.append("---")
    lines.append(f"Generated by Scientist OS (Megha). Research quality score: {m['rqs']:.2f}.")
    return "\n".join(lines)
